import assert from "node:assert/strict";
import { describe, it } from "vitest";
import { fixture, messages } from "./helpers.mjs";

const snippet = (name) => fixture(name);

describe("test and react same-file recall", () => {
  it("reports vitest sequential through aliases and static keys", () => {
    assert.equal(
      messages(
        snippet("no-vitest-sequential/recall.test.ts"),
        "no-vitest-sequential",
        undefined,
        "recall.test.ts",
      ).length,
      15,
    );
    assert.deepEqual(
      messages(
        snippet("no-vitest-sequential/created-runner.test.ts"),
        "no-vitest-sequential",
        undefined,
        "created-runner.test.ts",
      ),
      ["sequential"],
    );
    for (const name of [
      "renamed-fixture.test.ts",
      "default-import.test.ts",
      "module-function.test.ts",
      "module-let.test.ts",
      "module-var.test.ts",
    ]) {
      assert.deepEqual(
        messages(snippet(`no-vitest-sequential/${name}`), "no-vitest-sequential", undefined, name),
        ["sequential"],
      );
    }
    assert.deepEqual(
      messages(
        snippet("no-vitest-sequential/const-alias.test.ts"),
        "no-vitest-sequential",
        undefined,
        "const-alias.test.ts",
      ),
      ["sequential", "sequential"],
    );
  });

  it("treats an expression-free template require as a test import", () => {
    assert.deepEqual(
      messages(
        snippet("no-import-only-test-files/recall.test.js"),
        "no-import-only-test-files",
        undefined,
        "recall.test.js",
      ),
      ["aggregate"],
    );
    assert.deepEqual(
      messages(
        snippet("no-import-only-test-files/dynamic.test.js"),
        "no-import-only-test-files",
        undefined,
        "dynamic.test.js",
      ),
      [],
    );
    assert.deepEqual(
      messages(
        snippet("no-import-only-test-files/suppressed.test.js"),
        "no-import-only-test-files",
        undefined,
        "suppressed.test.js",
      ),
      [],
    );
    assert.deepEqual(
      messages(
        snippet("no-import-only-test-files/forwarded.test.js"),
        "no-import-only-test-files",
        undefined,
        "forwarded.test.js",
      ),
      ["aggregate"],
    );
    assert.deepEqual(
      messages(
        snippet("no-import-only-test-files/dynamic-forward.test.js"),
        "no-import-only-test-files",
        undefined,
        "dynamic-forward.test.js",
      ),
      [],
    );
    assert.deepEqual(
      messages(
        snippet("no-import-only-test-files/next-line.test.js"),
        "no-import-only-test-files",
        undefined,
        "next-line.test.js",
      ),
      [],
    );
  });

  it("recognizes vitest namespace module mocks and ignores the default export", () => {
    assert.deepEqual(
      messages(
        snippet("vitest-mock-test-file-naming/recall.test.ts"),
        "vitest-mock-test-file-naming",
        undefined,
        "recall.test.ts",
      ),
      ["needsMock"],
    );
    assert.deepEqual(
      messages(
        snippet("vitest-mock-test-file-naming/default.mock.test.ts"),
        "vitest-mock-test-file-naming",
        undefined,
        "default.mock.test.ts",
      ),
      ["unnecessaryMock"],
    );
    assert.deepEqual(
      messages(
        snippet("vitest-mock-test-file-naming/suppressed.test.ts"),
        "vitest-mock-test-file-naming",
        undefined,
        "suppressed.test.ts",
      ),
      [],
    );
  });

  it("reports error message assertions through expect aliases and static keys", () => {
    assert.equal(
      messages(
        snippet("test-no-error-message-matching/recall.test.ts"),
        "test-no-error-message-matching",
        undefined,
        "recall.test.ts",
      ).length,
      14,
    );
    for (const name of [
      "playwright-expect.test.ts",
      "setup-expect.test.ts",
      "bun-expect.test.ts",
      "chai-expect.test.ts",
      "cjs-expect.test.ts",
      "local-expect.test.ts",
      "function-expect.test.ts",
      "let-expect.test.ts",
    ]) {
      assert.deepEqual(
        messages(
          snippet(`test-no-error-message-matching/${name}`),
          "test-no-error-message-matching",
          undefined,
          name,
        ),
        ["message"],
      );
    }
    assert.deepEqual(
      messages(
        snippet("test-no-error-message-matching/bracket-call.test.ts"),
        "test-no-error-message-matching",
        undefined,
        "bracket-call.test.ts",
      ),
      ["message", "message"],
    );
    assert.deepEqual(
      messages(
        snippet("test-no-error-message-matching/binary-suppressed.test.ts"),
        "test-no-error-message-matching",
        undefined,
        "binary-suppressed.test.ts",
      ),
      ["message"],
    );
    assert.deepEqual(
      messages(
        snippet("test-no-error-message-matching/matcher-call.test.ts"),
        "test-no-error-message-matching",
        undefined,
        "matcher-call.test.ts",
      ),
      ["message", "message"],
    );
    assert.deepEqual(
      messages(
        snippet("test-no-error-message-matching/commonjs.test.cjs"),
        "test-no-error-message-matching",
        undefined,
        "commonjs.test.cjs",
        {},
        "commonjs",
      ),
      ["message"],
    );
  });

  it("reports shared state inside aliased and namespace test calls", () => {
    assert.equal(
      messages(
        snippet("test-no-shared-state/recall.test.ts"),
        "test-no-shared-state",
        undefined,
        "recall.test.ts",
      ).length,
      5,
    );
    assert.equal(
      messages(
        snippet("test-no-shared-state/computed-describe.test.ts"),
        "test-no-shared-state",
        undefined,
        "computed-describe.test.ts",
      ).length,
      1,
    );
    assert.equal(
      messages(
        snippet("test-no-shared-state/alias-describe.test.ts"),
        "test-no-shared-state",
        undefined,
        "alias-describe.test.ts",
      ).length,
      1,
    );
    assert.equal(
      messages(
        snippet("test-no-shared-state/sequence-describe.test.ts"),
        "test-no-shared-state",
        undefined,
        "sequence-describe.test.ts",
      ).length,
      1,
    );
    assert.equal(
      messages(
        snippet("test-no-shared-state/shadow-namespace.test.ts"),
        "test-no-shared-state",
        undefined,
        "shadow-namespace.test.ts",
      ).length,
      2,
    );
    assert.deepEqual(
      messages(
        snippet("test-no-shared-state/serial-alias.test.ts"),
        "test-no-shared-state",
        undefined,
        "serial-alias.test.ts",
      ),
      [],
    );
    assert.equal(
      messages(
        snippet("test-no-shared-state/shadow-test-alias.test.ts"),
        "test-no-shared-state",
        undefined,
        "shadow-test-alias.test.ts",
      ).length,
      1,
    );
    assert.deepEqual(
      messages(
        snippet("test-no-shared-state/namespace-serial.test.ts"),
        "test-no-shared-state",
        undefined,
        "namespace-serial.test.ts",
      ),
      [],
    );
    assert.equal(
      messages(
        snippet("test-no-shared-state/suppressed-alias.test.ts"),
        "test-no-shared-state",
        undefined,
        "suppressed-alias.test.ts",
      ).length,
      1,
    );
  });

  it("reports delayed rejects through renamed expect and static keys", () => {
    assert.equal(
      messages(
        snippet("test-no-delayed-rejects/recall.ts"),
        "test-no-delayed-rejects",
        undefined,
        "recall.ts",
      ).length,
      3,
    );
    assert.deepEqual(
      messages(
        snippet("test-no-delayed-rejects/poll.ts"),
        "test-no-delayed-rejects",
        undefined,
        "poll.ts",
      ),
      [],
    );
    assert.equal(
      messages(
        snippet("test-no-delayed-rejects/suppressed.ts"),
        "test-no-delayed-rejects",
        undefined,
        "suppressed.ts",
      ).length,
      1,
    );
  });
});

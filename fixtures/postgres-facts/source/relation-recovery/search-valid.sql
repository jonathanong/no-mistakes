WITH walk AS MATERIALIZED (SELECT 1 AS id) SEARCH BREADTH FIRST BY id SET ordercol SELECT * FROM walk;
WITH walk AS NOT MATERIALIZED (SELECT 1 AS id) SEARCH DEPTH FIRST BY id, parent SET ordercol SELECT * FROM walk;

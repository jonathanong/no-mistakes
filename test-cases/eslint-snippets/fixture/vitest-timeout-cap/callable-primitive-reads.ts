import { test, vi } from "vitest";
import { defineConfig } from "vitest/config";
const high = { timeout: () => 60_000 };
consume(high.timeout);
test("callable high value", high, () => {});
const low = { timeout: function () { return 1; } };
consume(low.timeout);
test("callable low value", low, () => {});
const getDeadline = () => 1;
const alias = { timeout: getDeadline };
consume(alias.timeout);
test("callable alias", alias, () => {});
const spread = { ...{ timeout: () => 60_000 } };
consume(spread.timeout);
test("callable spread", spread, () => {});
const nested = { inner: { timeout: () => null }, timeout: 1 };
consume(nested.inner.timeout);
test("nested callable", nested, () => {});
const numeric = { timeout: 1 };
consume(numeric.timeout);
test("genuine primitive", numeric, () => {});
const overCap = { timeout: 60_000 };
consume(overCap.timeout);
test("numeric high value", overCap, () => {});
// Config callbacks still project their bodies; scalar probing only checks runtime identity.
defineConfig(() => ({ test: { testTimeout: 1 } }));
defineConfig(function () { return { test: { testTimeout: 60_000 } }; });
const container = () => ({ testTimeout: 1 });
consume(container.testTimeout);
vi.setConfig(container);

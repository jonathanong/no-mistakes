import { test, beforeEach, vi } from "vitest";
import { defineConfig, defineProject, mergeConfig } from "vitest/config";
// Recognized option consumers do not expose the updated copied scalar.
const testSource = { timeout: 1, counter: 2 };
const testCopy = { ...testSource };
testCopy.counter++;
test("copy", testCopy, () => {});
test("source", testSource, () => {});
const hookSource = { timeout: 1, counter: 2 };
const hookCopy = { ...hookSource };
hookCopy.counter *= 2;
beforeEach(() => {}, hookCopy);
beforeEach(() => {}, hookSource);
const runtimeSource = { testTimeout: 1, counter: 2 };
const runtimeCopy = { ...runtimeSource };
runtimeCopy.counter--;
vi.setConfig(runtimeCopy);
vi.setConfig(runtimeSource);
const configSource = { test: { testTimeout: 1 }, counter: 2 };
const configCopy = { ...configSource };
configCopy.counter /= 2;
defineConfig(configCopy);
defineConfig(configSource);
const projectSource = { test: { testTimeout: 1 }, counter: 2 };
const projectCopy = { ...projectSource };
projectCopy.counter++;
defineProject(projectCopy);
defineProject(projectSource);
const mergeSource = { test: { testTimeout: 1 }, counter: 2 };
const mergeCopy = { ...mergeSource };
mergeCopy.counter++;
mergeConfig({}, mergeCopy);
defineConfig(mergeSource);
// Known high budgets are still reported after a supported copy consumer.
const highSource = { timeout: 60_000, counter: 2 };
const highCopy = { ...highSource };
highCopy.counter++;
test("high copy", highCopy, () => {});
test("high source", highSource, () => {});
// Arbitrary escapes, aliases, and invalid argument positions stay conservative.
const escaped = { timeout: 1, counter: 2 };
const escapedCopy = { ...escaped };
escapedCopy.counter++;
consume(escapedCopy);
test("escaped source", escaped, () => {});
const aliased = { timeout: 1, counter: 2 };
const aliasedCopy = { ...aliased };
const alias = aliasedCopy;
alias.counter = { valueOf() { return 0; } };
aliasedCopy.counter++;
test("aliased source", aliased, () => {});
const wrongPosition = { timeout: 1, counter: 2 };
const wrongCopy = { ...wrongPosition };
wrongCopy.counter++;
test(wrongCopy, () => {});
test("wrong-position source", wrongPosition, () => {});
// Shared child coercion remains unsafe even with recognized consumers.
const shared = { test: { testTimeout: 1, valueOf() { this.testTimeout = 60_000; return 0; } } };
const sharedCopy = { ...shared };
sharedCopy.test++;
defineConfig(sharedCopy);
defineConfig(shared);
// defineConfig returns its input; a returned alias may overwrite the copied scalar.
const returnedSource = { test: { testTimeout: 1 }, counter: 2 };
const returnedCopy = { ...returnedSource };
const returnedAlias = defineConfig(returnedCopy);
returnedAlias.counter = { valueOf() { returnedAlias.test.testTimeout = 60_000; return 0; } };
returnedCopy.counter++;
defineConfig(returnedSource);

import { it, beforeEach, vi } from "vitest";
const BASE = 15_000;
it("multiply", () => {}, 60 * 1000);
it("alias", () => {}, BASE * 3);
it("boundary", () => {}, 30 * 1000);
it("addition", () => {}, 30_000 + 1);
it("subtraction", () => {}, 60_001 - 30_000);
it("division", () => {}, 120_000 / 2);
it("remainder", () => {}, 90_001 % 60_000);
it("zero", () => {}, 30_000 - 30_000);
it("infinity", () => {}, 1 / 0);
it("nan", () => {}, 0 / 0);
it("string", () => {}, "60" * 1000);
it("dynamic", () => {}, Number(process.env.TIMEOUT) * 1000);
it("exponent", () => {}, 2 ** 16);
beforeEach(() => {}, { timeout: BASE * 3 });
vi.setConfig({ testTimeout: BASE * 3, hookTimeout: 5 * 1000 });
it("exponent boundary", () => {}, 30_000 ** 1);
it("exponent string", () => {}, "2" ** 16);
it("bitwise", () => {}, 1 << 16);

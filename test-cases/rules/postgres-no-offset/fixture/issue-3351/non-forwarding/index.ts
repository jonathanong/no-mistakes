import { query } from 'pg';
const transformed = (sql: string, values: unknown[]) => query(sql.trim(), values);
const reordered = (sql: string, values: unknown[]) => query(values, sql);
const dropped = (sql: string, values: unknown[]) => query(sql);
const spread = (sql: string, values: unknown[]) => query(...[sql, values]);
const defaulted = (sql = 'SELECT 1', values: unknown[]) => query(sql, values);
const shadowed = (query: Function, sql: string, values: unknown[]) => query(sql, values);
let mutable = (sql: string, values: unknown[]) => query(sql, values);
const droppedMiddle = (sql: string, values: unknown[], extra: unknown) => query(sql, extra);
const namedShadow = function query(sql: string, values: unknown[]) { return query(sql, values); };
transformed('SELECT 1', []);
reordered('SELECT 2', []);
dropped('SELECT 3', []);
spread('SELECT 4', []);
defaulted('SELECT 5', []);
shadowed(query, 'SELECT 6', []);
mutable('SELECT 7', []);
droppedMiddle('SELECT 8', [], 'wrong');
namedShadow('SELECT 9', []);

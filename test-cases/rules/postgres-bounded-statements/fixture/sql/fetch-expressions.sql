-- FETCH expressions retain typed quantity and source identity.
SELECT 1 FROM accounts FETCH FIRST (COALESCE(NULL, 100)) ROWS ONLY;
SELECT 1 FROM accounts FETCH NEXT (NULLIF(NULL::bigint, NULL::bigint)) ROWS ONLY;
SELECT 1 FROM accounts FETCH FIRST ($1::bigint) ROWS ONLY;
SELECT 1 FROM accounts FETCH FIRST ((SELECT count(*) FROM orders)) ROWS ONLY;
SELECT * FROM (SELECT 1 FROM accounts FETCH FIRST (100) ROWS ONLY) limited FETCH NEXT (2) ROWS ONLY;
SELECT id FROM accounts ORDER BY id FETCH FIRST (100) ROWS WITH TIES;
SELECT 1 FROM accounts OFFSET 5 ROWS FETCH FIRST (COALESCE(NULL, 100)) ROWS ONLY;
SELECT 1 FROM accounts FETCH FIRST ((SELECT count(*) FROM (SELECT id FROM orders LIMIT 1) limited)) ROWS ONLY;

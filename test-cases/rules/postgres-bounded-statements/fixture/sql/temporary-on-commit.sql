-- DROP identities disappear at commit; DELETE ROWS retains its temporary layout.
BEGIN;
CREATE TEMP TABLE accounts(id integer) ON COMMIT DROP;
DELETE FROM accounts;
COMMIT;
DELETE FROM accounts;
BEGIN;
CREATE TEMP TABLE accounts(id integer) ON COMMIT DELETE ROWS;
COMMIT;
DELETE FROM accounts;
DISCARD TEMP;
CREATE TEMP TABLE accounts(id integer) ON COMMIT DROP;
DELETE FROM accounts;
BEGIN;
CREATE TEMP TABLE accounts(id integer) ON COMMIT DROP;
ALTER TABLE accounts RENAME TO orders;
SET search_path = public, pg_temp;
COMMIT;
DELETE FROM orders;
RESET search_path;
BEGIN;
CREATE TEMP TABLE accounts(id integer) ON COMMIT DROP;
SAVEPOINT before_drop;
DROP TABLE accounts;
ROLLBACK TO before_drop;
COMMIT AND CHAIN;
DELETE FROM accounts;
ROLLBACK;
BEGIN;
CREATE TEMP TABLE accounts(id integer) ON COMMIT DROP;
ROLLBACK;
DELETE FROM accounts;

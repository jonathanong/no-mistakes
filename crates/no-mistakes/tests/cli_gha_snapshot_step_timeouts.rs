use super::check_json_snapshot::{assert_saved_fixture, rules_path};
use std::path::PathBuf;

const RULE: &str = "github-actions-step-timeouts";

fn case<'a>(label: &'a str, fixture: &str, config: &str) -> (&'a str, PathBuf, PathBuf) {
    (
        label,
        rules_path(RULE, "fixture", fixture),
        rules_path(RULE, "configs", config),
    )
}

#[test]
fn github_actions_step_timeouts_json_matches_snapshot() {
    let mut cases: Vec<(&str, PathBuf, PathBuf)> = Vec::new();
    for name in EMPTY {
        cases.push(case(name, name, "empty.yml"));
    }
    cases.extend([
        case("within_cap", "pass", "max-minutes-30.yml"),
        case("over_cap", "invalid", "max-minutes-10.yml"),
        case("github_ceiling", "invalid", "max-minutes-999.yml"),
        case("reasoned_allow", "allowed", "allow-reasoned.yml"),
        case("hash_allow", "hash-workflow", "hash-allow.yml"),
        case(
            "multi_file_allows",
            "multi-file-allows",
            "multi-file-allows.yml",
        ),
        case("blank_stale", "allowed", "blank-stale.yml"),
        case("stale_literal", "pass", "stale-literal.yml"),
        case("lower_cap", "lower-cap", "lower-cap.yml"),
        case("allow_invalid", "invalid", "allow-invalid.yml"),
        case("duplicate_allow", "allowed", "duplicate-allow.yml"),
        case("incomplete_selector", "pass", "incomplete-selector.yml"),
        case("duplicate_incomplete", "pass", "duplicate-incomplete.yml"),
        case("bad_yaml_duplicate", "bad-yaml", "bad-yaml-duplicate.yml"),
        case("include_miss", "missing", "include-other.yml"),
        case("parallel_allow", "parallel", "parallel-allow.yml"),
        case("no_jobs_allow", "no-jobs", "no-jobs-allow.yml"),
        // ci.yml is bounded; allow findings are for the absent deleted.yml.
        case("deleted_allow", "deleted-workflow", "deleted-allow.yml"),
    ]);
    assert_saved_fixture("github_actions_step_timeouts", &cases);
}


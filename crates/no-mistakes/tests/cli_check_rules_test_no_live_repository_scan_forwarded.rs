#[test]
fn forwarded_roots_check_json_snapshot() {
    let cases: Vec<(&str, PathBuf, PathBuf)> = CASES
        .iter()
        .map(|&name| {
            let root = crate::check_json_snapshot::rules_path(
                "test-no-live-repository-scan",
                "forwarded-roots",
                name,
            );
            (name, root.clone(), root.join(".no-mistakes.yml"))
        })
        .collect();
    let reports = crate::check_json_snapshot::assert_saved_fixture_report(
        "test_no_live_repository_scan_forwarded_roots",
        &cases,
        &[],
        &[],
    );
    forwarded_roots_preserve_positive_and_negative_controls(&reports);
}

fn forwarded_roots_preserve_positive_and_negative_controls(reports: &serde_json::Value) {
    let allowed = [
        "nullish-spread-owned",
        "nullish-empty-spread-owned",
        "nullish-nested-owned",
        "optional-present-owned",
        "dirname-alternative-children-owned",
        "object-computed-before-owned",
        "nested-array-owned",
        "empty-array-prefix-owned",
        "default-whole-member-owned",
        "default-computed-sibling-owned",
        "default-nested-sibling-owned",
        "rest-ternary-test-owned",
        "rest-not-test-owned",
        "rest-known-resolve-owned",
        "rest-assignment-expression-owned",
        "rest-nested-block-owned",
        "nullish-literal-owned",
        "undefined-literal-owned",
        "nullish-alias-owned",
        "nullish-property-owned",
        "wide-default-omitted-owned",
        "fallback-join-owned",
        "dirname-child-owned",
        "array-object-owned",
        "array-spread-owned",
        "default-omitted-owned",
        "default-owned",
        "default-scalar-owned",
        "fallback-or-owned",
        "fallback-owned",
        "fallback-relative-tail",
        "fallback-two-params-owned",
        "mock-local-alias-owned",
        "mock-rewrite-owned",
        "object-empty-owned",
        "object-literal-owned",
        "object-spread-owned",
        "optional-missing-owned",
        "rest-object-owned",
        "rest-owned",
        "rewrite-owned",
        "rewrite-owned-branch",
    ];
    for &name in CASES {
        let report = &reports[name]["report"];
        assert!(
            report["warnings"].as_array().unwrap().is_empty(),
            "{name}: {report}"
        );
        let found = ["rules", "advisories"].iter().any(|key| {
            report[*key]
                .as_array()
                .unwrap()
                .iter()
                .any(|finding| finding["rule"] == "test-no-live-repository-scan")
        });
        assert_eq!(found, !allowed.contains(&name), "{name}: {report}");
    }
}

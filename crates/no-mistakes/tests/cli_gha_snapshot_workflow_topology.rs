use super::check_json_snapshot::{assert_saved_fixture, rules_path};
use std::path::PathBuf;

const RULE: &str = "workflow-topology-policy";

fn configured(label: &'static str, root: &str, config: &str) -> (&'static str, PathBuf, PathBuf) {
    (
        label,
        rules_path(RULE, "fixture", root),
        rules_path(RULE, "configs", config),
    )
}

fn saved(label: &'static str, dir: &str, file: &str) -> (&'static str, PathBuf, PathBuf) {
    (
        label,
        rules_path(RULE, "fixture", dir),
        rules_path(RULE, "fixture", &format!("{dir}/{file}")),
    )
}

fn repository(label: &'static str, config: &str) -> (&'static str, PathBuf, PathBuf) {
    (
        label,
        no_mistakes::codebase::ts_resolver::normalize_path(
            &PathBuf::from(env!("CARGO_MANIFEST_DIR"))
                .join("../../test-cases/workflow-topology/repository"),
        ),
        rules_path(RULE, "configs", config),
    )
}

